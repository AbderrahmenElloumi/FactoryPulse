    patch = _git(work, "diff", "-U0", "HEAD~1", "HEAD", "--", "src/core.py").stdout
    assert re.findall(r"^[-+](?![-+]{2}).*$", patch, re.MULTILINE) == ["-VALUE = 1", "+VALUE = 2"]


